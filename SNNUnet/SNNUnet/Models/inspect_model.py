def print_model_summary(model: torch.nn.Module = None, 
                        device:str = 'cpu',
                        input_size:tuple = (32, 3, 224, 224),
                        mixed_precission: bool = False):
    """
    Function which prints summary of the model.

    Args:
        * model, torch.nn.Module, pytorch model
        * device, str, where the model and data are located, default is: cpu
        * input_dim, tupple, input dimenzions to the model
        * mixed_precission, bool, indicates if models is in full(32 bit) 
        or mixed precission (16 bit)

    Output:
        * returns printable model summary
    """
    # Apply precision
    _device = torch.device(device)
    with torch.autocast(device_type = _device.type) \
                if _device.type == 'cuda' and mixed_precission else DummyContext():
        
        return torchinfo.summary(model=model, 
                input_size= input_size,
                # col_names=["input_size"], # uncomment for smaller output
                col_names=["input_size", "output_size", "num_params", "trainable"],
                col_width=16,
                device = device,
                row_settings=["var_names"]) 


def main(data_fingerprint_path: str = None,
         device: str = None,
         export_dir: str = None):
    """
    Main funtion which build model from the dataset fingerprint and export all
    necessary files to the export dir including model description.

    Args:
        * data_fingerprint_path, str, path to the dataset fingerprint.
        * device, str, string, string representing device where model will be loaded. E.G. cuda:0, cuda:1, cpu...
        * export_dir, string, string representing path to the directory where model config will be saved and where
        model shape will be shown.

    Output:
        * print model and save model confing under the name "model_config.json"
    """
    # Create export dir if it does not exists
    os.makedirs(export_dir, exist_ok=True)

    # Create config
    _model_config = ModelConfig(path_to_data_fingerprint = data_fingerprint_path,
                                device = device,
                                device_limit = 9000,
                                mixed_precision = True)
    
    # Export import testing
    print(f"Export config to: {os.path.join(export_dir, 'model_config.json')}!")
    _model_config.export_to_json(export_path = os.path.join(export_dir, "model_config.json"))
    _model_config = ModelConfig()
    print(f"Import config from: {os.path.join(export_dir, 'model_config.json')}!")
    _model_config.import_from_json(import_path = os.path.join(export_dir, "model_config.json"))
    _model_config.max_batch_size = 2
    print(_model_config)
    
    # Build model, remember, model_config also have iter in it so this works :)
    _model = SNNUnet(**dict(_model_config))
    
    # Create input to the model
    _input_size = (_model_config.max_batch_size, 
                   _model_config.number_of_input_channels, 
                   *(_model_config.input_shape))

    # Print summary
    _summary = print_model_summary(model = _model,
                        input_size = _input_size,
                        device = "cuda:0",
                        mixed_precission = ModelConfig.mixed_precision)
    
    with open(os.path.join(export_dir, "model_inspection.txt"), "w") as _f:
        print(f"Summary:\n {_summary}", file = _f)
        print(f"Just model:\n {_model}", file = _f)
    

