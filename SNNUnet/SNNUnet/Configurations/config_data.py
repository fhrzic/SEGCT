"""
#*******************************************************************#
# Classes used as configuration for dataset, sampler and dataloader
#*******************************************************************#
"""
import json
import os

class DatasetConfig:
    '''
    ct_path: path to the ct directory contatining nifti files
    '''
    ct_path = None

    '''
    seg_path: path to the segmentation maps(niftis) directory
    '''
    seg_path = None

    '''
    loc_path: path to the potential locations
    '''
    loc_path = None

    '''
    data_fingerprint_path: path to dataingerprint file generated by GenerateDatasetFingerprint
    '''
    data_fingerprint_path = None

    '''
    patch_size: size of a patch in 3 dimensions (x,y,z)
    '''
    patch_shape = (128, 128, 128)

    '''
    minimum_fg: minimum numbers in patch which must belong to the foreground. Default 1%
    '''
    minimum_fg = 0.01

    '''
    multi_processing: integer(number_of_processes) or None for multiprocessing while 
    obtaining potential voxel places
    '''
    multiprocessing = None

    '''
    augmentation_config: if provided, it specifies which augmentations are being applied
    '''
    augmentation_method = None

    '''
    sample_limit, int, this is usefull during debugging to speed up training. It simply limits
    number of samples to the sample_limit number (it reduces the size of dataset). Defualt is None
    which means that whole dataset will be used.
    '''
    sample_limit = None

    '''
    keep_in_memmory: Keep all loaded data in memeory, if number given, then that is the "buffer" of 
    how many items (cases) will be hold in memory. The cases with most classes are prioritized to
    be loaded because they will be most likely selected for sampling. Set False to disable, or 
    percentage like 0.25 --> 25 percent of the cases will be held in memory
    '''
    keep_in_memory = False

    '''
    force_valid_locations: if set True, only patches which are fully inside the volume will be 
    obtained. Usefull in cases when there is no chance that the input volume will need to be 
    zero padded (input volume is smaller than patch size)
    '''
    force_valid_locations = False

    '''
    include_background_as_class, bool, if set to True, background will be used as any other
    class with sampling of the patches which contains the most of the background pixels. 
    A bit different sampling that for fg classes because in background case we actually must
    choose those patches that contains most of the background.
    '''
    include_background_as_class = False

    '''
    white_list_cases, list, list of the whitelist cases in case that we want to train
    model only on a subset of data
    '''
    white_list_cases = None

    def __str__(self):
        '''
        Just to check params
        '''
        _retval = ''
        _retval += ("######################################\n")
        _retval += ("DATASET\n")
        _retval += (f'ct_path: {DatasetConfig.ct_path}\n' + 
                    f'seg_path: {DatasetConfig.seg_path}\n' +
                    f'loc_path: {DatasetConfig.loc_path}\n' +
                    f'patch_size: {DatasetConfig.patch_shape}\n' +
                    f'minimum_fg: {DatasetConfig.minimum_fg}\n' +
                    f'data_fingerprint_path: {DatasetConfig.data_fingerprint_path}\n' +
                    f'multi_processing: {DatasetConfig.multiprocessing}\n' +
                    f'keep_in_memory: {DatasetConfig.keep_in_memory}\n' +
                    f'sample_limit: {DatasetConfig.sample_limit}\n' +
                    f'force_valid_locations: {DatasetConfig.force_valid_locations}\n' +
                    f'include_background_as_class: {DatasetConfig.include_background_as_class}\n' +
                    f'augmentation_config: {DatasetConfig.augmentation_method.__class__.__name__}\n' +
                    f'white_list_cases: {DatasetConfig.white_list_cases}\n')
        _retval += ("######################################\n")
        return _retval

    def export_to_json(
        self,
        export_path: str = None):
        """
        Method which exports the dict to the json. The default "used_dataset_fingerprint.json" 
        as the name is added only if the path already does not end with ".json". 
        In that case I assume that the exact file is provided.

        Args:
            * export_path, str, path to where the dict of the config elements will be stored. 
        """
        # Build dict:
        _output_dict = {"ct_path": DatasetConfig.ct_path,
                        "seg_path": DatasetConfig.seg_path,
                        "loc_path": DatasetConfig.loc_path,
                        "patch_shape": DatasetConfig.patch_shape,
                        "minimum_fg": DatasetConfig.minimum_fg,
                        "data_fingerprint_path": DatasetConfig.data_fingerprint_path,
                        "multiprocessing": DatasetConfig.multiprocessing,
                        "keep_in_memory": DatasetConfig.keep_in_memory,
                        "sample_limit": DatasetConfig.sample_limit,
                        "force_valid_locations": DatasetConfig.force_valid_locations,
                        "augmentation_method": DatasetConfig.augmentation_method.__class__.__name__,
                        "white_list_cases": DatasetConfig.white_list_cases}

         # In case that we want to export it
        if export_path is not None:
            # Modify name if dir is provided
            if not export_path.endswith(".json"):
                assert os.path.exists(export_path), (f"Path for the export does not exists. "
                                                     f"Please check path: {export_path}!")
                export_path = os.path.join(export_path, "used_dataset_fingerprint.json")

            # Dump it
            with open(export_path, "w") as _json_file:
                json.dump(_output_dict, _json_file, indent=4)
        else:
            print("export_path is None. Dict can not be exported!")

    def import_from_json(
        self,
        import_path: str = None):
        """
        Method which imports data from the provided import path and preloads whole
        class with imported data. 

        Args:
            * import_path, str, path to the "." json file which was exported
            by this class (method export_to_json)
        """
        # Check if file exists
        assert os.path.exists(import_path), (f"Path for the export does not exists. "
                                        f"Please check path: {import_path}!")

        # Read json to a dict
        with open(import_path, 'r') as _file:
            _imported_data = json.load(_file)

        # Transfer to variables
        DatasetConfig.ct_path = _imported_data["ct_path"]
        DatasetConfig.seg_path = _imported_data["seg_path"]
        DatasetConfig.loc_path = _imported_data["loc_path"]
        DatasetConfig.patch_shape = _imported_data["patch_shape"]
        DatasetConfig.minimum_fg = _imported_data["minimum_fg"]
        DatasetConfig.data_fingerprint_path = _imported_data["data_fingerprint_path"]
        DatasetConfig.multiprocessing = _imported_data["multiprocessing"]
        DatasetConfig.keep_in_memory = _imported_data["keep_in_memory"]
        DatasetConfig.sample_limit = _imported_data["sample_limit"]
        DatasetConfig.force_valid_locations = _imported_data["force_valid_locations"]
        DatasetConfig.augmentation_method = _imported_data["augmentation_method"]
        DatasetConfig.white_list_cases = _imported_data["white_list_cases"]

class SamplerConfig:
    '''
    Class for configuring sampler
    '''
    '''
    batch_size: size of the batch for the sampler
    '''
    batch_size = 8

    '''
    fg_sample_ratio: percentage of cases in batch that must be sampled from the 
    foreground
    '''
    fg_sample_ratio = 0.33

    '''
    dataset: dataset class which is in charge of generating data
    '''
    dataset = "Na"

    '''
    class_sampling_dict, dict, dictionary where key is class label and value
    is probability to sample this class. If it is string (like path to fingerprint)
    it will caluculate the probaiblity to sample each class based on the class properties.
    By class properties, I assume the number of foreground pixels of the class and then
    put it in a ratio.
    '''
    class_sampling_dict = None

    '''
    background_as_random, float, if set to a number, then this percentage of random will
    be sampled from the background label. This can also work with include_background_as_class
    in the dataset but it does not make any sence because then the background will be sampled 
    multiple times. Background values are always stored among the dataset labels, 
    '''
    background_as_random = None

    '''
    number_of_samples, integer, in case that we want to sample specific number of samples from 
    one case (sampler_for_validation), this paramter says how many sampels we want to sample
    in total. Then from each case in the dataset number_of_sample/number_of_cases_in_dataset
    will be sampled.
    '''
    number_of_samples = None

    def __str__(self):
        '''
        Just to check params
        '''
        _retval = ''
        _retval += ("######################################\n")
        _retval += ("SAMPLER\n")
        _retval += (f'batch_size: {SamplerConfig.batch_size}\n' + 
                    f'fg_sample_ratio: {SamplerConfig.fg_sample_ratio}\n' +
                    f'dataset: {SamplerConfig.dataset.__class__.__name__}\n' +
                    f'class_sampling_dict: {SamplerConfig.class_sampling_dict}\n' +
                    f'background_as_random: {SamplerConfig.background_as_random}\n' +
                    f'number_of_samples: {SamplerConfig.number_of_samples}\n')
        _retval += ("######################################\n")
        return _retval

    def export_to_json(
        self,
        export_path: str = None):
        """
        Method which exports the dict to the json. The default "sampler_fingerprint.json" 
        as the name is added only if the path already does not end with ".json". 
        In that case I assume that the exact file is provided.

        Args:
            * export_path, str, path to where the dict of the config elements will be stored. 
        """
        # Build dict:
        _output_dict = {"batch_size": SamplerConfig.batch_size,
                        "fg_sample_ratio": SamplerConfig.fg_sample_ratio,
                        "dataset": SamplerConfig.dataset.__class__.__name__,
                        "class_sampling_dict": SamplerConfig.class_sampling_dict,
                        "background_as_random": SamplerConfig.background_as_random,
                        "number_of_samples": SamplerConfig.number_of_samples}

         # In case that we want to export it
        if export_path is not None:
            # Modify name if dir is provided
            if not export_path.endswith(".json"):
                assert os.path.exists(export_path), (f"Path for the export does not exists. "
                                                     f"Please check path: {export_path}!")
                export_path = os.path.join(export_path, "sampler_fingerprint.json")

            # Dump it
            with open(export_path, "w") as _json_file:
                json.dump(_output_dict, _json_file, indent=4)
        else:
            print("export_path is None. Dict can not be exported!")

    def import_from_json(
        self,
        import_path: str = None):
        """
        Method which imports data from the provided import path and preloads whole
        class with imported data. 

        Args:
            * import_path, str, path to the "." json file which was exported
            by this class (method export_to_json)
        """
        # Check if file exists
        assert os.path.exists(import_path), (f"Path for the export does not exists. "
                                        f"Please check path: {import_path}!")

        # Read json to a dict
        with open(import_path, 'r') as _file:
            _imported_data = json.load(_file)

        # Transfer to variables
        SamplerConfig.batch_size = _imported_data["batch_size"]
        SamplerConfig.fg_sample_ratio = _imported_data["fg_sample_ratio"]
        SamplerConfig.dataset = _imported_data["dataset"]
        SamplerConfig.class_sampling_dict = _imported_data["class_sampling_dict"]
        SamplerConfig.background_as_fg_or_random = _imported_data["background_as_random"]
        SamplerConfig.number_of_samples = _imported_data["number_of_samples"]


class LoaderConfig:
    '''
    Class for defining loader parameters: batch_size, number of workers
    and gpu
    '''

    '''
    dataset: dataset class which is in charge of generating data
    '''
    dataset = None

    '''
    sampler: custom made sampler
    '''
    sampler = None

    '''
    number_of_workers: paralelization for data loading
    '''
    number_of_workers = 0

    '''
    prefetch_factor: number of batches that each worker prefetches
    '''
    prefetch_factor = 2

    '''
    use_gpu: set if the gpu is used
    '''
    use_gpu = False

    '''
    device: device to which the data will be loaded
    '''
