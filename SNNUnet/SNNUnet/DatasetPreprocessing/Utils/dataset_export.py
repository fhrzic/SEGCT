class DatasetExport():
    """
    Class for exporting the dataset to the numpy arrays preserving the same topological strucutre
    as in nifti files. The topological sturcutre is 

    ExportFolder:
        --> ct:
            --> 001.npy
            --> 002.npy
            --> ...
            --> ...
            --> nnn.npy
        --> seg:
            --> 001.npy
            --> 002.npy
            --> ...
            --> ...
            --> nnn.npy
        --> property:
            --> 001.npz
            --> 002.npz
            --> ...
            --> ...
            --> nnn.npz
    """

    def __init__(
        self,
        CT_files: str = None,
        seg_maps: str = None,
        normalization_fingerprint_json = None,
        normalization_method: str = "F",
        number_of_processes: int = None,
        number_of_samples_per_class: int = 10000):
        """
        Init function which serves to build up the class. IMPORTATNT IN CASE OF PROVIDING LISTS:
        The CT_files and seg_maps must be paired (1st file in CT_files must correspond to the 
        1st file in seg_maps).
        
        Args:
            * CT_files, string, string which represent path to the CTs (directory conatining CTs)
            * seg_maps, string, string which represent path to the segmentation maps (directory 
            conatining segmentation maps)
            * file_extension, string, extension of CT_files and seg_maps. Based on this extensions 
            the maps/files will be searched
            * normalization_fingerprint_json, string, path to the fingerprint file generated by 
            FingerprintGenerationScript.py 
            * normalization_method, str, a single letter representing normalization method for volume:
                - "F" - stands for normalization from fingerprint,
                - "V" - stands for normalization from volume,
                - "M" - stands for normalization from segmentation mask.
            For details on normalization methods, please see normalization.py script in DatasetPreprocessing/Utils
            * number_of_processes, int, number of processes assigned to this tas (enabels multiprocessing). 
            More processes --> more speed.
            * number_of_samples_per_class, int, number of how many smaples will be sotred per class per case. If it is set to
            None, all samples will be stored. I am following NNUnet convention of 10k samples.
        """

        ### Obtain CT_files
        # if it is list, just update self variable
        # if it is string, call method which seeks for nii.gz in given dir
        if isinstance(CT_files, list):
            self.CT_files = CT_files
        elif isinstance(CT_files, str):
            self.CT_files = self.__obtain_files(CT_files)
        else:
            raise ValueError("Variable CT_files must be either list or string")

        ### Obtain seg_maps
        # if it is list, just update self variable
        # if it is string, call method which seeks for nii.gz in given dir
        if isinstance(seg_maps, list):
            self.seg_maps = seg_maps
        elif isinstance(seg_maps, str):
            self.seg_maps = self.__obtain_files(seg_maps)
        else:
            raise ValueError("Variable seg_maps must be either list or string")

        ### Set number of processes
        self.number_of_processes = number_of_processes

        ### Obtain normalization
        assert normalization_method in ["F", "V", "M"], \
           "Error: Invalid normalization selection." + \
           f"Implemented normalizations methods are 'V', 'F', and 'M'! Got {normalization_method}!"
        if normalization_method == "F":
            self.CT_normalization = NormalizeCTFromFingerprint(
                path_to_fingerprint = normalization_fingerprint_json)
            self.SegMap_normalization = NormalizeSegmentationsFromFingerprint(
                path_to_fingerprint = normalization_fingerprint_json)
        
        if normalization_method == "V":
            self.CT_normalization = NormalizeCTFromVolume()
            self.SegMap_normalization = NormalizeSegmentationsFromFingerprint(
                path_to_fingerprint = normalization_fingerprint_json)
            
        if normalization_method == "M":
            self.CT_normalization = NormalizeCTFromMask()
            self.SegMap_normalization = NormalizeSegmentationsFromFingerprint(
                path_to_fingerprint = normalization_fingerprint_json)
        
        # Make it available
        self.normalization_method = normalization_method
        self.path_to_fingerprint = normalization_fingerprint_json
        self.number_of_samples_per_class = number_of_samples_per_class

    def __obtain_files(
        self,
        path_to_files:str = None,
        file_extension: str = "nii.gz")->list:
        """
        Method which lists the files in path_to_files and extract all files which ends 
        with file_extension

        Args:
            * path_to_files, str, path to the files 
            * file_extension, str, extension of the files which will be addet to the list

        Returns:
            * list of files found in a given "path_to_files" with extension given by 
            "file_extension". The file list is sorted so it will match. 
        """

        # Check if file exist
        assert os.path.exists(path_to_files), \
            f"Cant find: {path_to_files}! Please check the file path."

        # Check if it is directory
        assert os.path.isdir(path_to_files), \
            f"Not dir: {path_to_files}! Please check the file path is path to dir."

        # Obtain files
        _file_list = [os.path.join(path_to_files, _file) for 
                      _file in os.listdir(path_to_files) if _file.endswith(file_extension)]

        # Sort file list
        _file_list.sort()

        # Return
        return _file_list

    def __obtain_labels_locations(
            self,
            seg_map: np.ndarray = None,
            number_of_samples: int = 10000)->dict:
        """
        Method to obtain label location for each segmentation map and return dict where 
        key is label pixel value and value is list of locations

        Args:
            * seg_map, np.ndarray, volume representing segmentation map for which label 
            locations will be find
            * number_of_samples, int, number of samples to be sampled, in case that we want to
            limit number of locations per label. For instance, NNUnet uses 10000. Use None for
            all

        Returns:
            * dict, dictionary where key is label value and value is list of locations 
            where that label is present in volume
        
        """
        # Obtain labels one more time
        _unique_values = np.unique(seg_map.flatten())
        _unique_values = _unique_values[_unique_values != 0]  # Exclude 0 (background)

        # Storage dict
        _main_location_dict = {}
        # Obtain positions
        for _value in _unique_values:
            # Get indices
            _indices = np.argwhere(seg_map == _value)
            
            if number_of_samples is None:
                number_of_samples = len(_indices)
            else:
                number_of_samples = min(number_of_samples, len(_indices))

            # Select random numbers
            _random_indices = np.random.choice(len(_indices), size=number_of_samples, replace=False)            
            _indices = _indices[_random_indices]

            # Convert to uint16 to be sure
            _indices = [[[np.uint16(_coord) for _coord in _point]] for _point in _indices]

            # Since we are saving it to npz -> conversion to np.array is required
            _indices = np.array(_indices, dtype=np.uint16)
        
            # Store in dict
            _main_location_dict[str(_value)] = _indices

        # Obtain fg_to_bg ratio which is necessary for bg mining
        _fg_samples_count = sum(len(_values) for _values in _main_location_dict.values())
        _total_number_of_samples = seg_map.size
        _ratio = _fg_samples_count / _total_number_of_samples

        # Estimate number of voxels for background. We simply select the average of fg pixels
        # as a number of bg voxels
        _bg_samples = int(_fg_samples_count / len(_main_location_dict))

        # Obtain background proposals
        if _ratio < 0.75:
            # Small fg to bg ratio means a lot of background
            _background_indices_list = self.__obtain_background_coordinates_small_ratio(
                seg_map=seg_map,
                number_of_bg_samples = _bg_samples)
        else:
            # Big fg to bg ratio means no much background
            _background_indices_list = self.__obtain_background_coordinates_big_ratio(
                seg_map=seg_map,
                number_of_bg_samples = _bg_samples)

        # Add bg label
        _main_location_dict["0"] = _background_indices_list

        # Return
        return _main_location_dict

    def __obtain_background_coordinates_big_ratio(
            self,
            seg_map: np.ndarray = None,
            number_of_bg_samples: int = 1000)->List[Tuple[int,int,int]]:
        """
        Since fg to bg ratio is big, it means that we do not have a lot of background
        so random sampling might not work good. So we are calculating background 
        like it is another label: find all locations where voxels value is 0, then randomly
        sample number of samples. 
        
        Args:
            * seg_map, np.ndarray, this is the segmentation map
            * number_of_bg_samples, int, number of smapels which have to be sampled from the 
            volume

        Retruns:
            * list of tuples where each tuple represents coordinates of a voxel in the volume
        """
        # Get a mask of the background
        _background_mask = seg_map == 0

        # Get the total number of background voxels
        _background_count = np.sum(_background_mask)

        # Ensure n_samples is feasible
        _n_samples = min(number_of_bg_samples, _background_count)

        # Get all indices of the background voxels
        _background_indices = np.array(np.nonzero(_background_mask)).T  

        # Randomly sample indices
        _sampled_indices = np.random.choice(_background_indices.shape[0],
                                            size=_n_samples,
                                            replace=False)

        # Get the voxel coordinates of the sampled background voxels
        _sampled_background_voxels = _background_indices[_sampled_indices]

        # Convert to int
        _sampled_background_voxels = [[[int(_coord) for _coord in _point]] 
                                      for _point in _sampled_background_voxels]
        
        # Since we are saving it to npz -> conversion to np.array is required
        _sampled_background_voxels = np.array(_sampled_background_voxels, dtype=np.uint16)

        # Return
        return _sampled_background_voxels

    def __obtain_background_coordinates_small_ratio(
            self,
            seg_map: np.ndarray = None,
            number_of_bg_samples: int = 1000)->List[Tuple[int,int,int]]:
        """
        Since fg to bg ratio is small, it means that we have a lot of background so
        we can be efficient and randmomly sample coordinates from the volume, check
        if the selected coordinates points to the background and that is it.
        
        Args:
            * seg_map, np.ndarray, this is the segmentation map
            * number_of_bg_samples, int, number of smaples which have to be sampled from the 
            volume

        Retruns:
            * list of tuples where each tuple represents coordinates of a voxel in the volume
        """
        # Obtain shape
        _dims = seg_map.shape

        # Initialize a set for sampled voxels
        _sampled_background_voxels = []

        # Random sampling loop
        while len(_sampled_background_voxels) < number_of_bg_samples:
            # Generate random coordinates
            _rand_coords = tuple(np.random.randint(0, _dim) for _dim in _dims)

            # Check if the coordinate is background
            if seg_map[_rand_coords] == 0:
                _sampled_background_voxels.append(_rand_coords)

        # Convert set to a uint16
        _sampled_background_voxels = [[[np.uint16(_coord) for _coord in _point]] 
                                      for _point in _sampled_background_voxels]
        
        # Since we are saving it to npz -> conversion to np.array is required
        _sampled_background_voxels = np.array(_sampled_background_voxels, dtype=np.uint16)

        # Return
        return _sampled_background_voxels

    def __obtain_surface_labels_locations(
        self,
        seg_map: np.ndarray = None,
        min_blob_size: int = 10,
        number_of_samples: int = 10000)->dict:
        """
        Method which seeks for the voxels on the surface of the blobs for all labels
        and returns them like a dict. Similar to __obtain_labels_locations

        Args:
            * seg_map, np.ndarray, segmentation mask of the volume
            * min_blob_size, int, number of voxels to consider blob a blob. We set it to
            10 which is relatively small number for CTs but it can be adjusted. This is mainly
            to avoid errors in annotations.
        """
        # Obtain labels one more time
        _unique_values = np.unique(seg_map.flatten())
        _unique_values = _unique_values[_unique_values != 0]  # Exclude 0 (background)

        # Storage dict
        _main_location_dict = {}

        # Iterate over all classes
        for _class_value in _unique_values:
            # Create a binary mask for the current label
            _binary_mask = seg_map == _class_value

            # Find connected components
            _labeled_blobs, _num_blobs = label(_binary_mask)

            # Process each blob
            _all_border_coords = []
            for _blob_id in range(1, _num_blobs + 1):
                # Isolate the current blob
                _blob_mask = _labeled_blobs == _blob_id

                # Check the size of the blob
                if np.sum(_blob_mask) < min_blob_size:
                    continue  # Skip blobs smaller than the minimum size

                # Find the border: Dilate and subtract the original blob
                _border_mask = binary_dilation(_blob_mask) & ~_blob_mask

                # Get the coordinates of the border voxels
                _border_coords = np.array(np.nonzero(_border_mask)).T  # Shape (N, 3)

                # Add them to the pile
                _all_border_coords.extend(_border_coords)
            
            # Convert to int for json serialization
            _all_border_coords = [[[np.uint16(_coord) for _coord in _point]] 
                                  for _point in _all_border_coords]

            # Since we are saving it to npz -> conversion to np.array is required
            _all_border_coords = np.array(_all_border_coords, dtype=np.uint16)

            # Select samples
            if number_of_samples is None:
                number_of_samples = len(_all_border_coords)
            else:
                number_of_samples = min(number_of_samples, len(_all_border_coords))
            _random_indices = np.random.choice(len(_all_border_coords), size=number_of_samples, replace=False)
            _indices = _all_border_coords[_random_indices]
          
            # Now make dict
            if len(_indices) > 0:
                _main_location_dict[str(_class_value)] = _indices
            else:
                _main_location_dict[str(_class_value)] = []  # No border points available

        # Return
        return _main_location_dict

    def _export_case(
        self,
        case: list[str] = None):
        """
        Method which serves to export case and applies pre-processing normalization.

        Args:
            * case, list, list contatining two elements which represents path to the 
            ct volume and segmentation map.
        """
        # Unpack data
        _ct_path, _seg_mask_path = case

        # Read ct and seg_map
        # Read Volume
        _input_volume = sitk.ReadImage(_ct_path)
        _volume_numpy_array = sitk.GetArrayFromImage(_input_volume)    
        _volume_numpy_array = rearrange(_volume_numpy_array, 'z y x -> x y z')
        

        # Read mask
        _segmentation_mask = sitk.ReadImage(_seg_mask_path)
        _segmentation_numpy_array = sitk.GetArrayFromImage(_segmentation_mask)    
        _segmentation_numpy_array = rearrange(_segmentation_numpy_array, 'z y x -> x y z')
        _segmentation_numpy_array = _segmentation_numpy_array.astype(np.int32)

        # Crop to non-zero content (C, X, Y, Z) is required
        _cropped_volume, _cropped_segmentation_mask, _bbox = crop_to_nonzero(
            data = np.expand_dims(_volume_numpy_array, 0),
            seg = np.expand_dims(_segmentation_numpy_array, 0),
            nonzero_label = -1)

        # Squeeze added dim
        _cropped_volume = np.squeeze(_cropped_volume, 0)
        _cropped_segmentation_mask = np.squeeze(_cropped_segmentation_mask, 0)

        # Perform normalization for CT
        if self.normalization_method in ["F", "V"]:
            _volume_numpy_normalized = self.CT_normalization.run(_cropped_volume)
        else:
            # Mask requires also segmentation (M)
            _volume_numpy_normalized = self.CT_normalization.run(
                volume = _cropped_volume,
                segmentation =_cropped_segmentation_mask)

        _seg_map_numpy_normalized = self.SegMap_normalization.run(_cropped_segmentation_mask)

        # Obtain labels locations in a dict format
        _labels_location_dict = self.__obtain_labels_locations(
            seg_map = _seg_map_numpy_normalized,
            number_of_samples= self.number_of_samples_per_class)

        # Obtain surface locations in a dict format
        #_labels_surface_location_dict = self.__obtain_surface_labels_locations(
        #    seg_map = _seg_map_numpy_normalized,
        #    min_blob_size = 10,
        #    number_of_samples = self.number_of_samples_per_class )

        # In case that we need also 0, we add 0 to the surfaces dictionary. It is a copy of 0 in all
        # labels, but it is convinient to have all locations on one place-file
        #_labels_surface_location_dict["0"] =_labels_location_dict["0"]

        # Export everything
        _name_ct = _ct_path.split(os.path.sep)[-1]
        _name_ct = _name_ct.split(".nii")[0]
        _name_seg = _seg_mask_path.split(os.path.sep)[-1]
        _name_seg = _name_seg.split(".nii")[0]
        _volume_numpy_normalized = _volume_numpy_normalized.astype(np.float32)
        _seg_map_numpy_normalized = _seg_map_numpy_normalized.astype(np.int32)
        np.save(os.path.join(self.ct_dir, f"{_name_ct}.npy"), _volume_numpy_normalized)
        np.save(os.path.join(self.seg_dir, f"{_name_seg}.npy"), _seg_map_numpy_normalized)

        # Save
        np.savez_compressed(os.path.join(self.properties_dir, f"{_name_seg}.npz"), **_labels_location_dict)
        #np.savez_compressed(os.path.join(self.properties_dir, f"{_name_seg}_surfaces.npz"), **_labels_surface_location_dict)

   
    def export_data(self, dir_to_export_path: str = None):
        """
        Method which exports data to the directory by creating all sub directories in 
        it as described in the beggining of this class. DISCLAIMER: It always delete 
        the directory where the data will be exported.

        Args:
            * dir_to_export_path, str, path to the dir where data will be exported.
        """

        # Remove dir if exists
        if os.path.exists(dir_to_export_path):
            shutil.rmtree(dir_to_export_path)

        # Create_dirs
        os.makedirs(dir_to_export_path)
        self.ct_dir = os.path.join(dir_to_export_path, "img")
        self.seg_dir = os.path.join(dir_to_export_path, "seg")
        self.properties_dir = os.path.join(dir_to_export_path, "loc")
        os.makedirs(self.ct_dir)
        os.makedirs(self.seg_dir)
        os.makedirs(self.properties_dir)

        # Export files
        if self.number_of_processes is None:
            for _case in tqdm(zip(self.CT_files, self.seg_maps), total = len(self.CT_files)):
                self._export_case(_case)
        else:
            # Obtain all cases
            _all_cases = [*zip(self.CT_files, self.seg_maps)]

            # Define progress bar limit
            _progress_bar = tqdm(total = len(_all_cases))

            # Multi processing
            with multiprocessing.Pool(processes = self.number_of_processes) as _pool:
                # Submit tasks asynchronously and use the callback to update the progress
                for _input_data in _all_cases:
                    _result = _pool.apply_async(
                        self._export_case, 
                        args=(_input_data,), 
                        callback=lambda _: _progress_bar.update())

                # Close the pool to prevent any more tasks from being submitted
                _pool.close()

                # Wait for all worker processes to finish
                _pool.join()

            # Close progress bar
            _progress_bar.close()

    def export_normalization_fingerprint(self, 
                                         dir_to_export_path: str = None):
        """
        Method which exports normalization fingerprint so it can be used by the inference
        scripts.
        
        Args:
            * dir_to_export_path, str, path to the dir where data will be exported. 
        """
        # Create fingerprint
        _normalization_fingerprint = {"normalization_method": self.normalization_method}
         # Dump it
        with open(os.path.join(os.path.dirname(dir_to_export_path), "normalization_fingerprint.json"), "w") as _json_file:
            json.dump(_normalization_fingerprint, _json_file, indent=4)

