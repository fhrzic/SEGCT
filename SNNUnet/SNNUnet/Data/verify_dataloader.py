def main(export_dir_path = "DefaultDataExportDir",
         device = "cpu",
         path_to_data_fingerprint = None,
         ct_path = None,
         seg_path = None,
         loc_path = None):
    """
    Main function which do all the work. As an argument it accepts export_dir_path which defines where the 
    config files will be exported.

    Args:
        * export_dir_path, string, path to the export dir where all the config files are gonna be created.
        * device, string, device on which methods will we loaded. E.G. cuda:0, cuda:1, cpu
        * path_to_data_fingerprint, stirng, path to the data fingerprint generated by 
        generate_data_fingerprint_script
        * ct_path, string, path to the ct_files
        * seg_path, string, path to the segmentation files
        * loc_path, string, path to the location files
    """
    # Things we will need for all training
    _path_to_data_fingerprint = path_to_data_fingerprint
    _training_ctnpy_path      = ct_path
    _training_seg_path        = seg_path
    _training_loc_path        = loc_path
    _result_path              = export_dir_path

    _keep_in_memory = False
    _device = device
    # Create result path if it does not exists
    os.makedirs(_result_path, exist_ok=True)

    # Set up Augmentation because we are using custom one
    _augmentation_config = AugmentationConfigNNUnet()

    # Most of the things is already setup so no need to adjust
    AugmentationConfigNNUnet.s_ds_shapes_list = [[128,128,128], [64,64,64], [32,32,32]]
    AugmentationConfigNNUnet.a_rotation = True
    AugmentationConfigNNUnet.a_scaling = True
    AugmentationConfigNNUnet.a_mirror = True
    AugmentationConfigNNUnet.g_noise = False
    AugmentationConfigNNUnet.g_blur = False
    AugmentationConfigNNUnet.i_brightness = False
    AugmentationConfigNNUnet.i_contrast = False
    AugmentationConfigNNUnet.i_gamma_1 = False
    AugmentationConfigNNUnet.i_gamma_2 = False
    AugmentationConfigNNUnet.r_low_resolution = False
    AugmentationConfigNNUnet.c_center_crop = True
    AugmentationConfigNNUnet.s_ds_resize = True
    AugmentationConfigNNUnet.r_remove_label_transform = True
    AugmentationConfigNNUnet.c_cc_desired_patch_shape = [96,96,96]
    print(_augmentation_config)
    _augmentation_method = NNUnetAugmentation(augmentation_config = _augmentation_config)
    _augmentation_config.export_to_json(os.path.join(_result_path,"augmentation_config.json"))
   
    ################################################################################
    ################################################################################
    # Datasets
    _dataset_confing = DatasetConfig()
    # Dataset
    DatasetConfig.ct_path = _training_ctnpy_path
    DatasetConfig.seg_path = _training_seg_path
    DatasetConfig.loc_path = _training_loc_path
    DatasetConfig.data_fingerprint_path = _path_to_data_fingerprint
    DatasetConfig.patch_shape = [128,128,128]
    DatasetConfig.minimum_fg = 1e-7
    DatasetConfig.sample_limit_count = 1500
    DatasetConfig.multiprocessing = 30
    DatasetConfig.augmentation_method = _augmentation_method#_augmentation_method
    DatasetConfig.keep_in_memory = _keep_in_memory
    DatasetConfig.sample_limit = 5
    DatasetConfig.force_valid_locations = False
    DatasetConfig.include_background_as_class = False
    DatasetConfig.white_list_cases = None
    print(_dataset_confing)
    _dataset_confing.export_to_json(os.path.join(_result_path,"dataset_config.json"))
    # Create dataset
    _dataset = PatchDataset(_dataset_confing)

    # Training Sampler
    _sampler_config = SamplerConfig()
    SamplerConfig.batch_size = 8
    SamplerConfig.fg_sample_ratio = 0.33
    SamplerConfig.dataset = _dataset
    SamplerConfig.class_sampling_dict = None#_path_to_data_fingerprint#None
    SamplerConfig.background_as_random = None#0.33
    print(_sampler_config)
    _sampler_config.export_to_json(os.path.join(_result_path,"sampler_config.json"))

    # Create Sampler
    _sampler = NNUnetSampler(_sampler_config)

    # Training Dataloader 
    _dataloader_config = LoaderConfig()
    LoaderConfig.dataset = _dataset
    LoaderConfig.sampler = _sampler
    LoaderConfig.number_of_workers = 8
    LoaderConfig.prefetch_factor = 4
    LoaderConfig.use_gpu = False if _device == "cpu" else True
    LoaderConfig.device = _device
    LoaderConfig.collate_fn = custom_collate_fn_for_infinite_dataloader
    print(_dataloader_config)
    _dataloader_config.export_to_json(os.path.join(_result_path,"dataloader_config.json"))


    # Dataloader
    _training_dataloader = infinite_dataloader(_dataloader_config)

    # Test dataloader
    print("Testing the dataloader")
    i = 0
    for _item in _training_dataloader:
        #print(_item)
        print(i, _item[0].shape)
        if i == 10:
            break
        i+=1

    # Build from data

    build_data_loader_from_config(path_to_configs = _result_path)

def build_data_loader_from_config(path_to_configs = None):
    """
    Function which builds dataset from the config files. It serves for 
    testing purposes

    Args:
        * path_to_configs, str, path to the config files. Config files are:
        augmentation_config.json, dataset_config.json, sampler_config.json,
        dataloader_config.json

    Outputs:
        : Nothing
    """
    # Paths
    _path_to_aug = os.path.join(path_to_configs,"augmentation_config.json")
    _path_to_data = os.path.join(path_to_configs, "dataset_config.json")
    _path_to_sampler = os.path.join(path_to_configs, "sampler_config.json")
    _path_to_loader = os.path.join(path_to_configs, "dataloader_config.json")

    # Create augmentationt
    _augmentation_config = AugmentationConfigNNUnet()
    _augmentation_config.import_from_json(import_path = _path_to_aug)
    _augmentation_method = NNUnetAugmentation(augmentation_config = _augmentation_config)
    print(_augmentation_config)

    # Create dataset
    _dataset_confing = DatasetConfig()
    _dataset_confing.import_from_json(import_path = _path_to_data)
    DatasetConfig.augmentation_method = _augmentation_method if DatasetConfig.augmentation_method == _augmentation_method.__class__.__name__ else None
    print(_dataset_confing)
    _data = PatchDataset(_dataset_confing)

    # Create sampler
    _sampler_config = SamplerConfig()
    _sampler_config.import_from_json(import_path = _path_to_sampler)
    SamplerConfig.dataset = _data if SamplerConfig.dataset == _data.__class__.__name__ else None
    print(_sampler_config)
    _sampler = NNUnetSampler(_sampler_config)

    # Create dataloader
    _dataloader_config = LoaderConfig()
    _dataloader_config.import_from_json(import_path = _path_to_loader)
    LoaderConfig.dataset = _data if LoaderConfig.dataset == _data.__class__.__name__ else None
    LoaderConfig.sampler = _sampler if LoaderConfig.sampler == _sampler.__class__.__name__ else None
    LoaderConfig.collate_fn = custom_collate_fn_for_infinite_dataloader if LoaderConfig.collate_fn == "custom_collate_fn_for_infinite_dataloader" else None
    print(_dataloader_config)

    # Dataloader
    _dataloader = infinite_dataloader(_dataloader_config)

    # Test dataloader
    print("Testing the dataloader which was build from the loaded jsons!")
    for _item in _dataloader:
        print(_item)
        break

