"""
Script which transfer all necessary files to archive
conducted training and allow easy portability to other 
supercomputers and running inferece there
"""

import sys
import os
import shutil
import argparse

# Add project files
current_file_path = os.path.abspath(__file__)
main_dir =  os.path.dirname(os.path.dirname(current_file_path))
sys.path.append(main_dir)


def main(input_dir: str = None,
         archive_name: str = None):
    """
    Main method which replicates the structure of the input_dir to the
    TrainedModelsArchive dir inside SNNUnet under the name archive_name

    Args:
        * input_dir, str, input directory which is generated by training scripts
        which holds all necessary data to reproduce the model which was trained.
        * archive_name, str, name under this training will be archived.

    Outputs:
        * Check SNNUnet/TrainedModelArchive for the output

    DISCLAIMER: IT OVERRIDES THE OUTPUT DIR
    """
    _dir_path = os.path.join(main_dir, "TrainedModelsArchive", archive_name)

    # Remove it if it exists
    if os.path.isdir(_dir_path):
        shutil.rmtree(_dir_path)

    # (Re)create the directory
    os.makedirs(_dir_path)

    # Src files == files to be transfered.
    _data_fingerprint = os.path.join(input_dir, "training_fingerprint.json")
    _normalization_fingerprint = os.path.join(input_dir, "formated_data", "normalization_fingerprint.json")
    _configs = os.path.join(input_dir,"TRAINING", "Configs")
    _checkpoints = [os.path.join(input_dir,"TRAINING", "Checkpoints", _f) for _f in 
                    ["training_log.json", "last_checkpoint.pth", "best_model_checkpoint.pth", "best_model.pth"]]

    # Dst files == locations
    _dst_formated_dir = os.path.join(_dir_path, "formated_data")
    _dst_configs = os.path.join(_dir_path, "TRAINING", "Configs")
    _dst_checkpoints = os.path.join(_dir_path, "TRAINING", "Checkpoints")

    # Transfer
    # Data Fingerprint
    shutil.copy2(_data_fingerprint, _dir_path)   
    # Normalization fingerprint
    os.makedirs(_dst_formated_dir, exist_ok=True)
    shutil.copy2(_normalization_fingerprint, _dst_formated_dir)   
    # Configs
    shutil.copytree(_configs, _dst_configs)
    # Chcekpoints
    os.makedirs(_dst_checkpoints, exist_ok=True)
    for _f in _checkpoints:
        shutil.copy2(_f, _dst_checkpoints)


def cli():
    """
    Command-line interface: parse arguments and call main().
    """
    _parser = argparse.ArgumentParser(
        description="It only needs output dir and input dir... nothing else"
    )
    _parser.add_argument(
        "--input_dir",
        dest="input_dir",
        required=True,
        help="Path to the input directory which contains Trained model. Main dir of Training!"
    )

    _parser.add_argument(
        "--name",
        dest="name",
        required=True,
        help="Name of the Model, how it will be save in SNNUnet/TrainedModelsArchive dir"
    )
       
    _args = _parser.parse_args()

    main(input_dir = _args.input_dir,
         archive_name = _args.name)
    
  
if __name__ == "__main__":
    main()