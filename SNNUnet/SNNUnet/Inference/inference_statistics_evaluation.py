def cli():
    _parser = argparse.ArgumentParser(
        description="It only needs output dir and input dir... nothing else"
    )
    _parser.add_argument(
        "--input_dir_gt",
        dest="path_to_gt",
        required=True,
        help="Path to the ground truth. Either file or dir."
    )

    _parser.add_argument(
        "--input_dir_pred",
        dest="path_to_prediction",
        required=False,
        default=None,
        help="Path to the predictions. Either file or dir."
    )

    _parser.add_argument(
        "--output_dir",
        dest="export_path",
        required=True,
        help="Path to the output directory. (WARNING: APPEND or create if non-existant)"
    )
    
    _parser.add_argument(
        "--times_path",
        dest="times_path",
        required=False,
        help="Path to the times.json. Not mandatory."
    )

    _parser.add_argument(
        "--data_fingerprint",
        dest="data_fingerprint",
        required=True,
        help="Path to the JSON file containing dataset fingerprint"
    )

    _parser.add_argument(
        "--proc",
        dest="proc",
        required=True,
        type = int,
        help="Number of processes for multiprocessing."
    )
    
    # Parse args
    _args = _parser.parse_args()
    
    # Call main
    main(path_to_gt = _args.path_to_gt,
         path_to_prediction = _args.path_to_prediction,
         export_path = _args.export_path,
         times_path = _args.times_path,
         path_to_data_fingerprint = _args.data_fingerprint,
         number_of_processes = _args.proc)

def process_file(file_info: list = None):
    """
    Function to process a single file. Which is required
    for the multiprocessing.
    
    Args:
        * file_info, list, list cntaining path to gt segmentation, predicted segmentation
        and export path
    """
    # Parse input
    gt_segmentation_path, pred_segmentation_path, export_path = file_info

    # Obtain statistics
    obtain_statistics(
        gt_segmentation_path=gt_segmentation_path,
        pred_segmentation_path=pred_segmentation_path,
        export_path=export_path
    )

def main(
    path_to_gt: str = None,
    path_to_prediction: str = None,
    export_path: str = None,
    times_path: str = None,
    path_to_data_fingerprint: str = None,
    number_of_processes: int = None):
    """
    Main function for obtaining predictions. "path_to_gt" and "path_to_prediction" must
    be both either dir or file. In case of files, the comparison will be done for that file,
    but in case of the directory, the names in the gt dir will be seeken in the predictions dir 
    (without extension). In case that gt dir is same as prediction dir, then special naming must be
    used where gt is saved as "original_segmentation.nii.gz" and prediction is 
    "predicted_segmentation.nii.gz"

    Args:
        * path_to_gt, string, path to the ground truth. It can be either dir or 
        file. If this is dir, then also path_to_the_predictions must be dir. 
        * path_to_prediction, string, path to the predictions. It can be either file or dir but it 
        must be the same as path_to_gt
        * export_path, string, directory where results will be exported. 
        DICLAIMER: THE DIRECTORY WILL BE CREATE IF IT DOES NOT EXISTS. OTHERWISE THE DATA WILL BE
        APPENDED TO IT
        * times_path, str, path to the times.json generated by inference script. If not provided 
        (left None) the export of times will be skipped.
        * path_to__data_fingerprint, str, path to the fingerprint of the data. If not provided (left None)
        the export of merged statistics will be skipped
        * number_of_processes, int, if set to a value, number of processes which will be 
        utilized during the export
    """

    # Determine scenario
    # 0 file-file
    # 1 dir-dir
    # 2 dir1-dir2
    _scenario = None
    if os.path.isfile(path_to_gt) and os.path.isfile(path_to_prediction):
        _scenario = 0
    if os.path.isdir(path_to_gt) and\
        os.path.isdir(path_to_prediction) and\
        path_to_gt == path_to_prediction:
        _scenario = 1
    if os.path.isdir(path_to_gt) and\
        os.path.isdir(path_to_prediction) and\
        path_to_gt != path_to_prediction:
        _scenario = 2
    assert _scenario is not None, "Scenario not supported!"

    # Resolve scenario 0
    if _scenario == 0:
        # Create export dir
        if not os.path.exists(export_path):
            os.makedirs(export_path)
        print("Scenario 2: file-file")
        obtain_statistics(
            gt_segmentation_path = path_to_gt,
            pred_segmentation_path = path_to_prediction,
            export_path = export_path)

    # Resolve scenario 1
    if _scenario == 1:
        print("Scenario 1: dir-dir")
         # Obtain files
        _list_of_files = [os.path.join(path_to_gt, _file) for\
                        _file in os.listdir(path_to_gt) if os.path.isdir(os.path.join(path_to_gt,
                                                                                        _file))]
        # Create export dir
        if not os.path.exists(export_path):
            os.makedirs(export_path)

        # Check for single or multi processing
        if number_of_processes is None:
            # Export predictions
            for _file in tqdm(_list_of_files, desc = "Files:"):
                obtain_statistics(gt_segmentation_path = os.path.join(_file,
                                                                    "original_segmentation.nii.gz"),
                                pred_segmentation_path = os.path.join(_file,
                                                                    "predicted_segmentation.nii.gz"),
                                export_path = export_path)
        else:
            # Multiprocessing
            # Prepare file information
            _file_info_list = [
                (os.path.join(_file, "original_segmentation.nii.gz"),
                os.path.join(_file, "predicted_segmentation.nii.gz"),
                export_path)
                for _file in _list_of_files
            ]

            with Pool(processes=number_of_processes) as pool:
                list(tqdm(pool.imap_unordered(process_file, _file_info_list),
                          desc="Processing Files", 
                          total=len(_file_info_list)))

    # Resolve scenario 2
    if _scenario == 2:
        print("Scenario 2: dir1-dir2")
        # Obtain files (we sort in case of file name missmatch)
        _list_of_gt_files = [os.path.join(path_to_gt, 
                                          _file) for _file in os.listdir(path_to_gt)]
        _list_of_prediction_files = [os.path.join(path_to_prediction,
                                                  _file,
                                                  "predicted_segmentation.nii.gz")
                                                  for _file in os.listdir(path_to_prediction)]
        
        # To be causious, remove times.json and inference_config.json -- common mistake
        _list_of_prediction_files = [_f for _f in _list_of_prediction_files 
                                     if os.path.basename(os.path.dirname(_f)) not in ["times.json", "inference_config.json", "Statistics"]]
        
        # Sort
        print(len(_list_of_gt_files), len(_list_of_prediction_files))
        _list_of_gt_files.sort()
        _list_of_prediction_files.sort()

        for i,j in zip(_list_of_gt_files, _list_of_prediction_files):
            print(i,"\n", j)
            print("++++++++++++++++++++++++++++++++")
        # Create export dir
        if not os.path.exists(export_path):
            os.makedirs(export_path)

        # Check for single or multi processing
        if number_of_processes is None:
            # Export predictions
            for _gt_file, _pred_file in tqdm(zip(_list_of_gt_files,
                                    _list_of_prediction_files),
                                    total = len(_list_of_gt_files),
                                    desc = "Files:"):
                # Obtain prediction
                obtain_statistics(gt_segmentation_path = _gt_file, 
                                pred_segmentation_path = _pred_file,
                                export_path = export_path)
        else:    
            # Multiprocessing
            # Prepare file information
            _list_of_export_paths = [export_path for _ in _list_of_gt_files]
            _file_info_list = [_case for _case in zip(_list_of_gt_files,
                                                      _list_of_prediction_files,
                                                      _list_of_export_paths)]

            with Pool(processes=number_of_processes) as pool:
                list(tqdm(pool.imap_unordered(process_file, _file_info_list),
                          desc="Processing Files",
                          total=len(_file_info_list)))

    # After export, caluclate statistics
    if times_path is not None:
        print("Exporting times")
        plot_times(times_json_path = times_path,
                   output_path = export_path)
    # In case of scenario1 and scenario2 we export also merged statistics
    if (_scenario == 1 or _scenario == 2) and path_to_data_fingerprint is not None:
        merge_statistics(
            input_path = export_path, 
            path_to_fingerprint = path_to_data_fingerprint,
            output_path = export_path)

